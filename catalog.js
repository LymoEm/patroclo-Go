globalThis.PatrocloSearch = (() => {
  const normalize = value => value.toLowerCase().normalize('NFD').replace(/\p{M}/gu, '').match(/[a-z0-9]+/g) || [];
  const ignored = new Set('a al con como de del donde el en es horario la las los me para puedo que quiero se un una y'.split(' '));

  return (groups, query) => {
    const words = new Set(normalize(String(query ?? '')).filter(word => !ignored.has(word)));
    const matches = parts => [...new Set(normalize(parts.join(' ')))].filter(word => words.has(word)).length;
    return groups.map(group => ({
      group,
      score: 8 * matches([group.name, ...group.keywords]) +
        3 * matches([group.category, group.area, group.location]) +
        matches([group.description, group.requirements, group.contact, group.audience, group.benefits, group.join, group.schedule, group.dates])
    })).filter(item => item.score).sort((a, b) => b.score - a.score).map(item => item.group);
  };
})();

globalThis.PatrocloContent = (saved) => {
  const groups = globalThis.PatrocloCatalog;
  if (saved?.catalogVersion === 2) return saved;
  const history = {};
  const merged = groups.map(group => {
    const versions = saved?.history[group.id];
    const old = saved?.groups.find(item => item.id === group.id);
    if (!old || !versions?.length) return group;
    const original = versions.at(-1);
    const merge = record => {
      const updated = { ...group };
      for (const field of ['name', 'description', 'schedule', 'location', 'join']) {
        if (record[field] !== original[field]) updated[field] = record[field];
      }
      return updated;
    };
    history[group.id] = versions.map(merge);
    return merge(old);
  });
  return { catalogVersion: 2, groups: merged, history };
};
